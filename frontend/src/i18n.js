// ── Active language singleton ─────────────────────────────────────
const _saved = (() => { try { return localStorage.getItem('iow_lang'); } catch { return null; } })();
let _lang = (_saved && STRINGS[_saved]) ? _saved : 'en';

// English is the source of truth: keys missing in a translation fall back to it
const _withFallback = code => ({ ...STRINGS.en, ...STRINGS[code] });
export let T = _withFallback(_lang);

export function setLang(code) {
  if(!STRINGS[code]) return;
  _lang = code;
  T = _withFallback(code);
  try { localStorage.setItem('iow_lang', code); } catch {}
  // Toggle body classes for language-specific CSS (letter-spacing, font)
  document.body.classList.toggle('lang-vi', code === 'vi');
  document.body.classList.toggle('lang-fr', code === 'fr');
  document.body.classList.toggle('lang-ja', code === 'ja');
  // Broadcast so all open panels can re-render
  window.dispatchEvent(new CustomEvent('iow:langchange', { detail: code }));
}

export function getLang() { return _lang; }
